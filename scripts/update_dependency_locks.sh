#!/usr/bin/env bash
set -euo pipefail

project_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "${project_root}"

project_venv="${THREATBRIDGE_VENV:-.venv}"
python_bin="${project_venv}/bin/python"
pip_compile="${project_venv}/bin/pip-compile"
output_dir="${1:-requirements}"

mkdir -p "${output_dir}"

{
    echo "# Generated by scripts/update_dependency_locks.sh from pyproject.toml [build-system].requires; do not edit."
    "${python_bin}" -c \
        'import tomllib; print("\n".join(tomllib.load(open("pyproject.toml", "rb"))["build-system"]["requires"]))'
} > "${output_dir}/build.in"

export CUSTOM_COMPILE_COMMAND="./scripts/update_dependency_locks.sh"
common_options=(
    --allow-unsafe
    --generate-hashes
    --no-annotate
    --no-header
    --no-emit-index-url
    --no-emit-trusted-host
    --resolver=backtracking
    --strip-extras
)

"${pip_compile}" "${common_options[@]}" \
    --output-file "${output_dir}/build.txt" \
    "${output_dir}/build.in"
"${pip_compile}" "${common_options[@]}" \
    --output-file "${output_dir}/runtime.txt" \
    pyproject.toml
"${pip_compile}" "${common_options[@]}" \
    --extra dev \
    --output-file "${output_dir}/development.txt" \
    pyproject.toml

"${python_bin}" scripts/lock_file_metadata.py \
    "${output_dir}/build.txt" \
    "${output_dir}/runtime.txt" \
    "${output_dir}/development.txt"
