#!/usr/bin/env python3
from __future__ import annotations

import re
import sys
import tomllib
from dataclasses import dataclass
from pathlib import Path

from packaging.requirements import Requirement
from packaging.version import Version

try:
    from scripts.lock_file_metadata import LOCK_HEADERS
except ModuleNotFoundError:  # Direct execution places scripts/ on sys.path.
    from lock_file_metadata import LOCK_HEADERS

PROJECT_ROOT = Path(__file__).resolve().parent.parent
PROHIBITED_SOURCE = re.compile(
    r"(?im)(?:https?|ftp|file)://|(?:git|hg|svn|bzr)\+|"
    r"^\s*--(?:index-url|extra-index-url|trusted-host|find-links|no-index)\b|"
    r"^\s*-(?:r|c)\s+"
)
PINNED_REQUIREMENT = re.compile(
    r"^([A-Za-z0-9][A-Za-z0-9_.-]*)==([^\s;\\]+)(?:\s*;\s*[^\\]+)?\s*\\$"
)
HASH_LINE = re.compile(r"^\s+--hash=sha256:([0-9a-f]{64})(?:\s*\\)?$")
NORMALIZE_NAME = re.compile(r"[-_.]+")
BUILD_INPUT_HEADER = (
    "# Generated by scripts/update_dependency_locks.sh from "
    "pyproject.toml [build-system].requires; do not edit."
)


@dataclass(frozen=True)
class LockedPackage:
    name: str
    version: Version
    hashes: frozenset[str]


def normalized_name(value: str) -> str:
    return NORMALIZE_NAME.sub("-", value).lower()


def parse_lock(path: Path) -> dict[str, LockedPackage]:
    source = path.read_text(encoding="utf-8")
    header = "\n".join(LOCK_HEADERS[path.name]) + "\n\n"
    if not source.startswith(header):
        raise ValueError(f"{path}: missing or incorrect generated-file metadata")
    body = source[len(header) :]
    prohibited = PROHIBITED_SOURCE.search(body)
    if prohibited is not None:
        raise ValueError(f"{path}: prohibited dependency source or pip directive")

    packages: dict[str, LockedPackage] = {}
    current_name: str | None = None
    current_version: Version | None = None
    current_hashes: set[str] = set()

    def finish_package() -> None:
        nonlocal current_name, current_version, current_hashes
        if current_name is None or current_version is None:
            return
        if not current_hashes:
            raise ValueError(f"{path}: {current_name} has no SHA-256 hashes")
        if current_name in packages:
            raise ValueError(f"{path}: duplicate package {current_name}")
        packages[current_name] = LockedPackage(
            name=current_name,
            version=current_version,
            hashes=frozenset(current_hashes),
        )
        current_name = None
        current_version = None
        current_hashes = set()

    for line_number, line in enumerate(body.splitlines(), start=len(LOCK_HEADERS[path.name]) + 2):
        if not line or line.startswith("#"):
            continue
        if line[0].isspace():
            hash_match = HASH_LINE.fullmatch(line)
            if current_name is None or hash_match is None:
                raise ValueError(f"{path}:{line_number}: malformed hash continuation")
            digest = hash_match.group(1)
            if digest in current_hashes:
                raise ValueError(f"{path}:{line_number}: duplicate SHA-256 hash")
            current_hashes.add(digest)
            continue

        finish_package()
        match = PINNED_REQUIREMENT.fullmatch(line)
        if match is None:
            raise ValueError(f"{path}:{line_number}: dependency is not exactly pinned")
        current_name = normalized_name(match.group(1))
        current_version = Version(match.group(2))

    finish_package()
    if not packages:
        raise ValueError(f"{path}: lock is empty")
    return packages


def required_packages(requirements: list[str]) -> dict[str, Requirement]:
    parsed = (Requirement(requirement) for requirement in requirements)
    return {normalized_name(requirement.name): requirement for requirement in parsed}


def validate_requirements(
    lock_path: Path,
    packages: dict[str, LockedPackage],
    requirements: dict[str, Requirement],
) -> None:
    missing = sorted(requirements.keys() - packages.keys())
    if missing:
        raise ValueError(f"{lock_path}: missing direct dependencies: {', '.join(missing)}")
    for name, requirement in requirements.items():
        version = packages[name].version
        if requirement.specifier and version not in requirement.specifier:
            raise ValueError(
                f"{lock_path}: {name}=={version} violates {requirement.specifier}"
            )


def validate_runtime_parity(
    runtime_path: Path,
    runtime_packages: dict[str, LockedPackage],
    development_path: Path,
    development_packages: dict[str, LockedPackage],
) -> None:
    missing = sorted(runtime_packages.keys() - development_packages.keys())
    if missing:
        raise ValueError(
            f"{development_path}: missing runtime packages: {', '.join(missing)}"
        )

    for name, runtime_package in runtime_packages.items():
        development_package = development_packages[name]
        if development_package.version != runtime_package.version:
            raise ValueError(
                f"{development_path}: runtime package {name} has version "
                f"{development_package.version}; expected {runtime_package.version} "
                f"from {runtime_path}"
            )
        missing_hashes = runtime_package.hashes - development_package.hashes
        if missing_hashes:
            raise ValueError(
                f"{development_path}: runtime package {name} is missing compatible "
                "SHA-256 hashes"
            )


def validate_build_input(path: Path, expected: list[str]) -> None:
    lines = path.read_text(encoding="utf-8").splitlines()
    if not lines or lines[0] != BUILD_INPUT_HEADER:
        raise ValueError(f"{path}: missing or incorrect generated-file metadata")
    if lines[1:] != expected:
        raise ValueError(f"{path}: does not match pyproject.toml [build-system].requires")


def validate_locks(project_root: Path = PROJECT_ROOT) -> dict[str, int]:
    pyproject_path = project_root / "pyproject.toml"
    with pyproject_path.open("rb") as handle:
        pyproject = tomllib.load(handle)

    requirements_dir = project_root / "requirements"
    build_requirements = list(pyproject["build-system"]["requires"])
    runtime_requirements = list(pyproject["project"]["dependencies"])
    development_requirements = list(
        pyproject["project"]["optional-dependencies"]["dev"]
    )
    validate_build_input(requirements_dir / "build.in", build_requirements)

    build_path = requirements_dir / "build.txt"
    runtime_path = requirements_dir / "runtime.txt"
    development_path = requirements_dir / "development.txt"
    build_packages = parse_lock(build_path)
    runtime_packages = parse_lock(runtime_path)
    development_packages = parse_lock(development_path)
    validate_runtime_parity(
        runtime_path,
        runtime_packages,
        development_path,
        development_packages,
    )

    validate_requirements(
        build_path, build_packages, required_packages(build_requirements)
    )
    runtime_direct = required_packages(runtime_requirements)
    validate_requirements(runtime_path, runtime_packages, runtime_direct)
    development_direct = runtime_direct | required_packages(development_requirements)
    validate_requirements(development_path, development_packages, development_direct)

    return {
        "build": len(build_packages),
        "runtime": len(runtime_packages),
        "development": len(development_packages),
    }


def main() -> None:
    try:
        counts = validate_locks()
    except (KeyError, OSError, TypeError, ValueError) as error:
        print(f"Dependency lock validation failed: {error}", file=sys.stderr)
        raise SystemExit(1) from error
    print(
        "Validated committed hashed locks: "
        + ", ".join(f"{name}={count}" for name, count in counts.items())
        + "."
    )


if __name__ == "__main__":
    main()
